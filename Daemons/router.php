/**
 * Function to check notification rules logic agains event parameters. This
 * function was called recursively to process sub logic rules.
 *
 * @param array &$rules Rules array. Function will append "result" boolean to
 *                      each rule and to array root with overall logic result.
 * @param array $parameters Array containing the event parameters.
 * @return boolean Result of final rule logic.
 */
function check_rules ( &$rules, $parameters)
{
  foreach ( $rules as $key => $value)
  {
    if ( $key == "rules")
    {
      foreach ( $value as $id => $rule)
      {
        if ( array_key_exists ( "rules", $rule))
        {
          check_rules ( $rules[$key][$id], $parameters);
          continue;
        }
        switch ( $rule["operator"])
        {
          case "equal":
          case "not_equal":
            switch ( $rule["type"])
            {
              case "string":
              case "time":
                $rules[$key][$id]["result"] = (string) $parameters[$rule["field"]] == (string) $rule["value"];
                break;
              case "number":
              case "integer":
              case "date":
              case "datetime":
                $rules[$key][$id]["result"] = (int) $parameters[$rule["field"]] == (int) $rule["value"];
                break;
              case "double":
                $rules[$key][$id]["result"] = (float) $parameters[$rule["field"]] == (float) $rule["value"];
                break;
              case "boolean":
                $rules[$key][$id]["result"] = (bool) $parameters[$rule["field"]] == (bool) $rule["value"];
                break;
            }
            break;
          case "in":
          case "not_in":
            $rules[$key][$id]["result"] = in_array ( $parameters[$rule["field"]], $rule["value"], true);
            break;
          case "less":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] < $rule["value"][0];
            break;
          case "less_or_equal":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] <= $rule["value"][0];
            break;
          case "greater":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] > $rule["value"][0];
            break;
          case "greater_or_equal":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] >= $rule["value"][0];
            break;
          case "between":
          case "not_between":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] >= $rule["value"][0] && $parameters[$rule["field"]] <= $rule["value"][1];
            break;
          case "begins_with":
          case "not_begins_with":
            $rules[$key][$id]["result"] = substr ( $parameters[$rule["field"]], 0, strlen ( $rule["value"])) == $rule["value"];
            break;
          case "contains":
          case "not_contains":
            $rules[$key][$id]["result"] = strpos ( $parameters[$rule["field"]], $rule["value"]) !== false;
            break;
          case "ends_with":
          case "not_ends_with":
            $rules[$key][$id]["result"] = substr ( $parameters[$rule["field"]], strlen ( $rule["value"]) * -1) == $rule["value"];
            break;
          case "is_empty":
          case "is_not_empty":
            $rules[$key][$id]["result"] = $parameters[$rule["field"]] === "";
            break;
          case "is_null":
          case "is_not_null":
            $rules[$key][$id]["result"] = is_null ( $parameters[$rule["field"]]);
            break;
        }
        if ( substr ( $rule["operator"], 0, 4) == "not_" || $rule["operator"] == "is_not_empty" || $rule["operator"] == "is_not_null")
        {
          $rules[$key][$id]["result"] = ! $rules[$key][$id]["result"];
        }
      }
    }
  }

  // Check logic
  switch ( $rules["condition"])
  {
    case "OR":
      $result = false;
      foreach ( $rules["rules"] as $rule)
      {
        if ( $rule["result"])
        {
          $result = true;
          break;
        }
      }
      break;
    case "AND":
      $result = true;
      foreach ( $rules["rules"] as $rule)
      {
        if ( ! $rule["result"])
        {
          $result = false;
          break;
        }
      }
      break;
  }
  if ( array_key_exists ( "not", $rules) && $rules["not"] == true)
  {
    $result = ! $result;
  }
  $rules["result"] = $result;

  return $result;
}

/**
 * Function to reload notifications from database.
 *
 * @global array $_in Framework Main configuration variable
 * @param void
 * @return boolean
 */
function reload_notifications ()
{
  global $_in;

  // Check if database connection are alive
  mysql_check ();

  // Fetch data
  if ( ! $result = @$_in["mysql"]["id"]->query ( "SELECT * FROM `Notifications`"))
  {
    writeLog ( "Cannot fetch notifications from database!", VoIP_LOG_WARNING);
    return false;
  }

  // Populate notifications variable
  $_in["Notifications"] = array ();
  while ( $notification = $result->fetch_assoc ())
  {
    $notification["Headers"] = json_decode ( $notification["Headers"], true);
    $notification["Filters"] = json_decode ( $notification["Filters"], true);
    $notification["Variables"] = json_decode ( $notification["Variables"], true);
    $_in["Notifications"][] = $notification;
  }

  return true;
}

/**
 * Reload router in-memory caches from authoritative sources.
 *
 * Optional parameters:
 *   - ServerID: clear monitoring cache for one server only
 *
 * @global array $_in Framework global configuration variable
 * @param string $buffer Buffer from plugin system if processed by other function
 *                       before
 * @param array $parameters Optional parameters to the function
 * @return array
 */
function router_reload_cache ( $buffer, $parameters)
{
  global $_in;

  if ( ! is_array ( $buffer))
  {
    $buffer = array ( "events" => array (), "return" => "");
  }
  if ( ! array_key_exists ( "events", $buffer))
  {
    $buffer["events"] = array ();
  }
  if ( ! array_key_exists ( "return", $buffer))
  {
    $buffer["return"] = "";
  }

  reload_notifications ();
  $_in["keys"] = array ();

  /**
   * Reload server/tenant keys from database
   */
  mysql_check ();
  if ( $result = @$_in["mysql"]["id"]->query ( "SELECT `Servers`.`ID`, `Servers`.`PublicKey`, `Tenants`.`PrivateKey` AS `TenantPrivateKey` FROM `Servers` LEFT JOIN `Tenants` ON `Servers`.`Tenant` = `Tenants`.`ID`"))
  {
    while ( $row = $result->fetch_assoc ())
    {
      $_in["keys"]["server_" . $row["ID"]] = array (
        "publicKey" => $row["PublicKey"],
        "tenantPrivateKey" => $row["TenantPrivateKey"]
      );
    }
    $result->free ();
  }

  if ( array_key_exists ( "ServerID", $parameters) && preg_match ( "/^[0-9]+$/", (string) $parameters["ServerID"]))
  {
    $serverid = (int) $parameters["ServerID"];
    unset ( $_in["Channels"][$serverid]);
    unset ( $_in["Queues"][$serverid]);
    unset ( $_in["Peers"][$serverid]);
    writeLog ( "Router cache reloaded for server #" . $serverid . ".");
  } else {
    $_in["Channels"] = array ();
    $_in["Queues"] = array ();
    $_in["Peers"] = array ();
    writeLog ( "Router cache reloaded.");
  }

  return $buffer;
}

/**
 * Handle systemd reload by detecting new plugins and restarting if needed,
 * or just refreshing caches if no plugin changes detected.
 *
 * @param int $signo Signal number
 * @return void
 */
function router_systemd_reload_handler ( $signo)
{
  global $_in;

  $pluginsdir = dirname ( __FILE__) . "/router-plugins";
  $new_plugins_detected = false;
  if ( is_dir ( $pluginsdir))
  {
    $current_plugins = array ();
    foreach ( scandir ( $pluginsdir) as $entry)
    {
      if ( $entry == "." || $entry == "..")
      {
        continue;
      }
      if ( is_dir ( $pluginsdir . "/" . $entry))
      {
        $current_plugins[] = $entry;
      }
    }
    if ( ! array_key_exists ( "loaded_plugins", $_in))
    {
      $_in["loaded_plugins"] = array ();
    }
    $diff = array_diff ( $current_plugins, $_in["loaded_plugins"]);
    if ( sizeof ( $diff) > 0)
    {
      $new_plugins_detected = true;
      writeLog ( "New plugin(s) detected in router-plugins/: " . implode ( ", ", $diff) . ". Exiting for restart.", VoIP_LOG_NOTICE);
    }
  }

  if ( $new_plugins_detected)
  {
    writeLog ( "Router exiting cleanly for systemd restart to load new plugins (signal " . $signo . ").", VoIP_LOG_NOTICE);
    exit ( 0);
  }

  router_reload_cache ( array ( "events" => array (), "return" => ""), array ());
  writeLog ( "Router cache reloaded from systemd signal " . $signo . ".", VoIP_LOG_NOTICE);
}

/**
 * Process pending commands from the database queue.
 * This watchdog function re-sends commands that were queued but not delivered
 * (e.g., when Gearman was unavailable at the time of the original request).
 *
 * @global array $_in Framework global configuration variable
 * @param GearmanClient $gm_client Gearman client for sending commands
 * @return int Number of commands processed
 */
function process_pending_commands ( $gm_client)
{
  global $_in;

  if ( ! $gm_client)
  {
    return 0;
  }

  // Check database connection
  mysql_check ();

  // Fetch pending commands with server information
  $query = "SELECT c.`ID`, c.`Server`, c.`Event`, c.`Data`, s.`PublicKey`, t.`PrivateKey` AS TenantPrivateKey
            FROM `Commands` c
            INNER JOIN `Servers` s ON c.`Server` = s.`ID`
            INNER JOIN `Tenants` t ON s.`Tenant` = t.`ID`
            WHERE s.`PublicKey` IS NOT NULL AND s.`PublicKey` != ''
            ORDER BY c.`ID` ASC
            LIMIT 100";

  if ( ! $result = @$_in["mysql"]["id"]->query ( $query))
  {
    writeLog ( "Watchdog: Failed to fetch pending commands", VoIP_LOG_WARNING);
    return 0;
  }

  $processed = 0;
  while ( $command = $result->fetch_assoc ())
  {
    // Skip if no tenant private key
    if ( empty ( $command["TenantPrivateKey"]))
    {
      continue;
    }

    // Prepare payload
    $data = json_decode ( $command["Data"], true);
    $payload = json_encode ( array (
      "event" => $command["Event"],
      "id" => $command["ID"],
      "data" => $data,
      "group" => null
    ));

    // Encrypt payload
    $iv = secure_rand ( 16, true);
    $key = secure_rand ( 256, true);
    $encrypted = openssl_encrypt ( $payload, "aes-256-cbc", $key, OPENSSL_RAW_DATA, $iv);
    $hmac = hash_hmac ( "sha256", $encrypted, $key, true);

    if ( ! openssl_public_encrypt ( $key, $encryptedkey, $command["PublicKey"]))
    {
      writeLog ( "Watchdog: Failed to encrypt key for command #" . $command["ID"], VoIP_LOG_WARNING);
      continue;
    }

    if ( ! openssl_sign ( $key . $iv . $hmac . $encrypted, $sign, $command["TenantPrivateKey"], OPENSSL_ALGO_SHA256))
    {
      writeLog ( "Watchdog: Failed to sign payload for command #" . $command["ID"], VoIP_LOG_WARNING);
      continue;
    }

    // Send via Gearman
    $task_name = gearman_client_task_name ( $command["Server"]);
    $task_data = json_encode ( array (
      "payload" => base64_encode ( $encrypted),
      "iv" => base64_encode ( $iv),
      "key" => base64_encode ( $encryptedkey),
      "hmac" => base64_encode ( $hmac),
      "sign" => base64_encode ( $sign)
    ));

    try
    {
      $gm_client->doBackground ( $task_name, $task_data);
      $processed++;

      if ( ! empty ( $_in["general"]["debug"]))
      {
        writeLog ( "Watchdog: Re-sent command #" . $command["ID"] . " to server #" . $command["Server"], VoIP_LOG_NOTICE);
      }
    }
    catch ( Exception $e)
    {
      writeLog ( "Watchdog: Failed to send command #" . $command["ID"] . ": " . $e->getMessage (), VoIP_LOG_WARNING);
      break;
    }
  }

  if ( $processed > 0)
  {
    writeLog ( "Watchdog: Re-sent " . $processed . " pending command(s)", VoIP_LOG_NOTICE);
  }

  return $processed;
}
