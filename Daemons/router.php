$_in["watchdog"]["last_check"] = 0;

/**
 * Start Gearman worker
 */
while ( true)
{
  /**
   * Connect to gearman servers
   */
  $gearman_host = ! empty ( $_in["gearman"]["hostname"]) ? $_in["gearman"]["hostname"] : "127.0.0.1";
  $gearman_port = ! empty ( $_in["gearman"]["port"]) ? $_in["gearman"]["port"] : 4730;
  try
  {
    $gm = new GearmanWorker ();
    if ( ! @$gm->addServer ( $gearman_host, $gearman_port))
    {
      throw new Exception ( "addServer returned false");
    }
    $gm->setTimeout ( 5000);
  } catch ( Exception $e)
  {
    writeLog ( "Cannot connect to Gearman at ${gearman_host}:${gearman_port}: " . $e->getMessage (), VoIP_LOG_WARNING);
    sleep ( 5);
    continue;
  }

  /**
   * Create Gearman client for sending pending commands
   */
  try
  {
    $gm_client = new GearmanClient ();
    $gm_client->addServer ( $gearman_host, $gearman_port);
  } catch ( Exception $e)
  {
    writeLog ( "Cannot create Gearman client: " . $e->getMessage (), VoIP_LOG_WARNING);
    $gm_client = null;
  }

  /**
   * Register worker functions
   */
  foreach ( $_plugins["hooks"] as $hook => $function)
  {
    $gm->addFunction ( $hook, "gearman_event");
  }

  /**
   * Register task worker for plugin system dispatch
   */
  $gm->addFunction ( "vd_router_task", "router_gearman_task_handler");
  writeLog ( "Gearman task worker registered: vd_router_task");

  /**
   * Loop waiting for work!
   */
  while ( true)
  {
    @$gm->work ();

    if ( $gm->returnCode () == GEARMAN_TIMEOUT)
    {
      // Timeout - check for pending commands
      if ( time () - $_in["watchdog"]["last_check"] >= $_in["watchdog"]["interval"])
      {
        process_pending_commands ( $gm_client);
        $_in["watchdog"]["last_check"] = time ();
      }
      continue;
    }

    if ( $gm->returnCode () != GEARMAN_SUCCESS)
    {
      break;
    }
  }

  /**
   * If exited loop, all gearman servers was gone!
   */
  writeLog ( "Gearman servers disconnected! Retrying in 5 seconds.", VoIP_LOG_WARNING);
  unset ( $gm);
  unset ( $gm_client);
  sleep ( 5);
}

/**
 * Gearman framework hook system wrapper.
 *
 * @global array $_in Framework global configuration variable
 * @param $job object Gearman Job object.
 * @return (mixed) Hook output.
 */
function gearman_event ( $job)
{
  global $_in;

  // Dump event if debug enabled
  if ( ! empty ( $_in["general"]["debug"]))
  {
    echo "Event \"" . $job->functionName () . "\" received: ";
  }

  // Get workload
  $workload = json_decode ( $job->workload (), 1);

  // Call job hook with exception protection
  try
  {
    $result = framework_call ( $job->functionName (), $workload, false, array ( "events" => array (), "return" => ""));
  } catch ( Throwable $e)
  {
    writeLog ( "Event \"" . $job->functionName () . "\" threw " . get_class ( $e) . ": " . $e->getMessage () . " in " . $e->getFile () . ":" . $e->getLine (), VoIP_LOG_WARNING);
    $trace_lines = explode ( "\n", $e->getTraceAsString ());
    foreach ( array_slice ( $trace_lines, 0, 5) as $trace_line)
    {
      writeLog ( "  " . $trace_line, VoIP_LOG_WARNING);
    }
    return "";
  }

  // Check for notification events:
  foreach ( $result["events"] as $event)
  {
    foreach ( $_in["Notifications"] as $notification)
    {
      if ( $notification["Event"] == $event["event"])
      {
        // Validate rules:
        if ( sizeof ( $notification["Rules"]) != 0 && check_rules ( $notification["Rules"], $event["parameters"]))
        {
          echo "Notification event match!\n";
        }
      }
    }
  }

  // Return event data:
  return $result["return"];
}

/**
 * Gearman task handler for plugin system dispatch (config sync, module deploy, etc.)
 *
 * @param $job object Gearman Job object.
 * @return string JSON response.
 */
function router_gearman_task_handler ( $job)
{
  $payload = json_decode ( $job->workload (), true);
  if ( ! is_array ( $payload) || ! array_key_exists ( "hook", $payload))
  {
    writeLog ( "Gearman task received with invalid payload.", VoIP_LOG_WARNING);
    return json_encode ( array ( "result" => false, "error" => "Invalid payload"));
  }
  writeLog ( "Gearman task received: " . $payload["hook"]);
  $taskdata = array_key_exists ( "data", $payload) ? $payload["data"] : array ();
  try
  {
    $result = framework_call ( $payload["hook"], $taskdata, false, "");
  } catch ( Throwable $e)
  {
    writeLog ( "Task \"" . $payload["hook"] . "\" threw " . get_class ( $e) . ": " . $e->getMessage () . " in " . $e->getFile () . ":" . $e->getLine (), VoIP_LOG_WARNING);
    return json_encode ( array ( "result" => false, "error" => $e->getMessage ()));
  }
  return json_encode ( array ( "result" => true, "data" => $result));
}

