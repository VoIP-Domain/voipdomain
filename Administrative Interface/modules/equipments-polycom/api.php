framework_add_hook ( "tenants_add_post", "equipments_polycom_tenant_add_post");

/**
 * Function to add default Polycom equipments settings to new tenant.
 *
 * @global array $_in Framework global configuration variable
 * @param string $buffer Buffer from plugin system if processed by other function
 *                       before
 * @param array $parameters Optional parameters to the function
 * @return string Output of the generated page
 */
function equipments_polycom_tenant_add_post ( $buffer, $parameters)
{
  global $_in;

  foreach ( array ( "spip301", "spip430") as $uid)
  {
    if ( ! @$_in["mysql"]["id"]->query ( "INSERT INTO `Config` (`Key`, `Tenant`, `Data`) VALUES ('Equipment_" . $_in["mysql"]["id"]->real_escape_string ( $uid) . "', " . (int) $parameters["ID"] . ", '{\"AudioCodecs\":[\"ULAW\",\"ALAW\",\"G729\",\"G722\"],\"VideoCodecs\":[],\"ExtraSettings\":[]}')"))
    {
      header ( $_SERVER["SERVER_PROTOCOL"] . " 503 Service Unavailable");
      exit ();
    }
  }

  return $buffer;
}
